/** Lista de redes sociais em botões redondos */
export function SocialLinks({ className, size = 'md', limit }: { className?: string; size?: 'sm' | 'md'; limit?: number }) {
  const links = [
    { href: config.social.instagram, label: 'Instagram', Icon: InstagramIcon },
    { href: config.social.youtube, label: 'YouTube', Icon: YouTubeIcon },
    { href: config.streaming.spotify, label: 'Spotify', Icon: SpotifyIcon },
    { href: config.social.tiktok, label: 'TikTok', Icon: TikTokIcon },
    { href: config.social.facebook, label: 'Facebook', Icon: FacebookIcon },
  ]
    .filter((l) => l.href)
    .slice(0, limit);

  return (
    <ul className={cn('flex items-center gap-2', className)}>
      {links.map(({ href, label, Icon }) => (
        <li key={label}>
          <a
            href={href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={label}
            title={label}
            className={cn(
              'flex items-center justify-center rounded-full border border-white/15 text-cream/80 transition-all duration-300 hover:-translate-y-0.5 hover:border-gold-500 hover:bg-gold-500 hover:text-ink-950',
              size === 'sm' ? 'size-9' : 'size-11'
            )}
          >
            <Icon className={size === 'sm' ? 'size-4' : 'size-[18px]'} />
          </a>
        </li>
      ))}
    </ul>
  );
}
